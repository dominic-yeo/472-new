#!/usr/bin/env python3
"""
agentic_authority.py -- quantify potentially security-relevant authority paths
in the annotated agentic graphs.

This does NOT claim runtime enforcement or universal root-cause. It reports three
*structural* tiers, computed directly from each app's agentic_gt.yaml:

  (1) PRIVILEGED TOOLS  -- tool_bindings whose effect_class can act on the world
      (code_execution | external_send | write | mixed). A capability classification,
      not a vulnerability.

  (2) UNTRUSTED-REACHABLE PRIVILEGED TOOLS -- of (1), those bound to an agent that
      also ingests at least one context_source with trust_class in
      {untrusted_data, mixed}. This is a *structural path* in the annotated graph
      (untrusted input -> same agent -> privileged tool), established by a join on
      the agent node. It is NOT evidence that the path was exercised, nor that it
      is exploitable.

  (3) RUNTIME-OBSERVED -- of (2), those whose tool_binding record is
      evidence_status: observed. Even here, "observed" means the tool was seen to
      run; it does NOT mean a control was seen to fire.

Control accounting is by RECORDED control_ids only: "no control" means no control
is recorded in the dataset for that binding, NOT that the application has none.
"""
import glob, os, sys, yaml

PRIV = {"code_execution", "external_send", "write", "mixed"}
UNTRUSTED = {"untrusted_data", "mixed"}

def load(p):
    with open(p, encoding="utf-8") as f:
        return yaml.safe_load(f) or {}

def analyse(doc):
    agents = {a["id"]: a for a in (doc.get("agents") or [])}
    tools = doc.get("tool_bindings") or []
    ctxs = {c["id"]: c for c in (doc.get("context_sources") or [])}
    controls = doc.get("controls") or []

    # agent -> does it ingest any untrusted/mixed context source?
    untrusted_fed = set()
    for c in ctxs.values():
        if c.get("trust_class") in UNTRUSTED:
            for aid in (c.get("destination_agent_ids") or []):
                untrusted_fed.add(aid)
    for a in agents.values():
        for cid in (a.get("context_source_ids") or []):
            c = ctxs.get(cid)
            if c and c.get("trust_class") in UNTRUSTED:
                untrusted_fed.add(a["id"])

    priv = [t for t in tools if t.get("effect_class") in PRIV]
    reachable = [t for t in priv if t.get("agent_id") in untrusted_fed]
    reach_no_ctl = [t for t in reachable if not (t.get("control_ids") or [])]
    reach_ctl = [t for t in reachable if (t.get("control_ids") or [])]

    codex = [t for t in tools if t.get("effect_class") == "code_execution"]
    codex_gated = [t for t in codex
                   if (t.get("control_ids") or [])
                   or str(t.get("approval_required")).lower() in {"true", "required", "yes"}]
    codex_reach = [t for t in codex if t.get("agent_id") in untrusted_fed]

    observed_reach = [t for t in reachable if t.get("evidence_status") == "observed"]

    untrusted_ctx = [c for c in ctxs.values() if c.get("trust_class") in UNTRUSTED]

    enf = {}
    for c in controls:
        m = c.get("enforcement_mode")
        enf[m] = enf.get(m, 0) + 1

    return dict(
        agents=len(agents), tools=len(tools),
        untrusted_ctx=len(untrusted_ctx), untrusted_agents=len(untrusted_fed & set(agents)),
        priv=len(priv), reachable=len(reachable),
        reach_ctl=len(reach_ctl), reach_no_ctl=len(reach_no_ctl),
        codex=len(codex), codex_gated=len(codex_gated), codex_reach=len(codex_reach),
        observed_reach=len(observed_reach),
        controls=len(controls), enf=enf,
        no_ctl_ids=[t["id"] for t in reach_no_ctl],
    )

def main():
    root = os.path.dirname(os.path.abspath(__file__))
    os.chdir(root)
    rows = []
    tot = dict(agents=0, tools=0, untrusted_ctx=0, priv=0, reachable=0, reach_ctl=0,
               reach_no_ctl=0, codex=0, codex_gated=0, codex_reach=0, observed_reach=0,
               controls=0)
    enf_tot = {}
    no_ctl_all = []
    for p in sorted(glob.glob("*_gt/agentic_gt.yaml")):
        app = os.path.dirname(p).replace("_gt", "")
        r = analyse(load(p))
        rows.append((app, r))
        for k in tot:
            tot[k] += r[k]
        for m, n in r["enf"].items():
            enf_tot[m] = enf_tot.get(m, 0) + n
        no_ctl_all += [f"{app}:{i}" for i in r["no_ctl_ids"]]

    def line(app, r):
        return (f"| {app} | {r['priv']} | {r['reachable']} | {r['reach_no_ctl']} "
                f"| {r['codex']} ({r['codex_gated']} gated) | {r['observed_reach']} |")

    out = []
    out.append("# Agentic authority-path characterization\n")
    out.append("_Generated by `agentic_authority.py` over the five `*_gt/agentic_gt.yaml` files._\n")
    out.append("Structural counts in the annotated graphs. Not runtime-enforcement, "
               "not exploitability, not a universal root cause.\n")
    out.append("| app | privileged tools | untrusted-reachable | reachable w/ no recorded control | code-exec | runtime-observed (of reachable) |")
    out.append("|---|--:|--:|--:|--:|--:|")
    for app, r in rows:
        out.append(line(app, r))
    out.append(f"| **TOTAL** | **{tot['priv']}** | **{tot['reachable']}** | "
               f"**{tot['reach_no_ctl']}** | **{tot['codex']} ({tot['codex_gated']} gated)** "
               f"| **{tot['observed_reach']}** |")
    out.append("")
    out.append(f"- Untrusted-or-mixed context sources feeding agents: **{tot['untrusted_ctx']}**")
    out.append(f"- Privileged tool bindings (effect_class in {sorted(PRIV)}): **{tot['priv']}**")
    out.append(f"- Of those, structurally reachable from an untrusted/mixed context source "
               f"(same-agent join): **{tot['reachable']}**")
    out.append(f"- Of the reachable, with >=1 recorded control: **{tot['reach_ctl']}**; "
               f"with NO recorded control: **{tot['reach_no_ctl']}**")
    out.append(f"- Code-execution tools: **{tot['codex']}**, of which gated by a recorded "
               f"control or approval flag: **{tot['codex_gated']}**")
    out.append(f"- Runtime-observed (evidence_status=observed) among reachable privileged tools: "
               f"**{tot['observed_reach']}** (observed = tool seen to run, NOT control seen to fire)")
    out.append(f"- Controls by enforcement_mode: {dict(sorted(enf_tot.items()))} "
               f"(declared mode; not runtime-verified)")
    out.append(f"- Reachable privileged tools with no recorded control: {no_ctl_all}")
    report = "\n".join(out) + "\n"
    with open("authority_report.md", "w", encoding="utf-8") as f:
        f.write(report)
    print(report)

if __name__ == "__main__":
    main()
